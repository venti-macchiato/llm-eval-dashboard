CACHE_TTL = 30.0
_cache: dict | None = None
_cache_at = 0.0


class SandboxError(Exception):
    """Raised when a task needs a capability the host does not provide."""


def _normalise(task: str) -> str:
    return re.sub(r"^inspect_evals/", "", str(task).strip()).lower()


def required(task: str) -> list[str]:
    """Capabilities a task needs before it can run."""
    return ["docker"] if _normalise(task) in DOCKER_TASKS else []


def clear_cache() -> None:
    """Forget the cached capability probe (used by tests and retries)."""
    global _cache, _cache_at
    _cache = None
    _cache_at = 0.0


def docker_status(refresh: bool = False) -> dict:
    """``{available, detail}`` for the Docker daemon, cached briefly."""
    global _cache, _cache_at
    now = time.monotonic()
    if not refresh and _cache is not None and now - _cache_at < CACHE_TTL:
        return _cache
    try:
        proc = subprocess.run(
            DOCKER_CMD, capture_output=True, text=True, timeout=10
        )
    except FileNotFoundError:
        status = {"available": False, "detail": "docker CLI not found on PATH"}
    except (OSError, subprocess.SubprocessError) as exc:
        status = {"available": False, "detail": f"{type(exc).__name__}: {exc}"}
    else:
        if proc.returncode == 0 and proc.stdout.strip():
            status = {"available": True, "detail": proc.stdout.strip()}
        else:
            lines = (proc.stderr or proc.stdout).strip().splitlines()
            detail = lines[0][:200] if lines else f"docker exited with {proc.returncode}"
            status = {"available": False, "detail": detail}
    _cache = status
    _cache_at = now
    return status


def capabilities(refresh: bool = False) -> dict:
    return {"docker": docker_status(refresh)}


def missing(tasks: list[str], refresh: bool = False) -> dict[str, list[str]]:
    """Map task -> missing capabilities. Empty when everything can run."""
    wanted = [(task, required(task)) for task in tasks]
    wanted = [(task, reqs) for task, reqs in wanted if reqs]
    if not wanted:
        # Nothing selected needs a capability: do not spawn docker at all.
        return {}
    caps = capabilities(refresh)
    lacking: dict[str, list[str]] = {}
    for task, reqs in wanted:
        absent = [req for req in reqs if not caps.get(req, {}).get("available")]
        if absent:
            lacking[task] = absent
    return lacking


def ensure(tasks: list[str]) -> None:
    """Raise SandboxError with an actionable message if a task cannot run."""
    lacking = missing(tasks, refresh=True)
    if not lacking:
        return
    names = ", ".join(sorted({_normalise(task) for task in lacking}))
    detail = docker_status().get("detail") or "unknown error"
    raise SandboxError(
        f"{names} needs Docker, which is not available ({detail}). "
        "Start Docker Desktop and retry, or choose a task that runs without a sandbox."
    )
